#!/usr/bin/env python3
# s5r2_appendix.py -- generate checkpoints/p05/P05_S5R2_GATE_APPENDIX.md from the formal end-gate
# output ($EV/gate/GATE_S5R2_end.txt). The report only references this file; it does not embed the
# gate results. Writes outside $EV, so it does not break "sha_sums is the last $EV write".
import os,sys,re,hashlib,subprocess
REPO=subprocess.check_output(["git","rev-parse","--show-toplevel"],text=True).strip()
P05=os.path.join(REPO,"checkpoints/p05")
EV=os.path.join(P05,"evidence/p05-s5r2")
GATE=os.path.join(EV,"gate","GATE_S5R2_end.txt")
OUT=os.path.join(P05,"P05_S5R2_GATE_APPENDIX.md")
TAB=chr(9); NL=chr(10); FENCE=chr(96)*3
def rd(p): return open(p,encoding="utf-8").read()
def sha_f(p):
 h=hashlib.sha256()
 with open(p,"rb") as f:
  for b in iter(lambda:f.read(65536),b""): h.update(b)
 return h.hexdigest()
def main():
 if not os.path.isfile(GATE): print("HARD_STOP formal gate file missing: "+GATE); return 2
 lines=rd(GATE).splitlines()
 counts=[l for l in lines if l.startswith("COUNTS")]
 fails=[l for l in lines if l.startswith("FAILS=")]
 crashed=[l for l in lines if "CHECK_CRASHED_ZERO" in l]
 post=[l for l in lines if "POST_I_CALL_COUNT" in l]
 faildetail=[l for l in lines if l.startswith("FAIL"+TAB)]
 excl=[l for l in lines if l.startswith("RECORD"+TAB+"EXCLUDED")]
 records=[l for l in lines if l.startswith("RECORD"+TAB)]
 if not counts or not fails:
  print("HARD_STOP gate file lacks COUNTS/FAILS"); return 2
 body=[]
 body.append("# P05-S5 R2 end gate appendix (P05_S5R2_GATE_APPENDIX.md)")
 body.append("")
 body.append("> Generated by testing/d003/stage_s5r2/s5r2_appendix.py from the single formal end-gate run")
 body.append("> (checkpoints/p05/evidence/p05-s5r2/gate/GATE_S5R2_end.txt). The report body only references this file.")
 body.append("")
 body.append("- GATE_FILE_SHA256="+sha_f(GATE))
 body.append("- GATE_LINES=%d"%len(lines))
 body.extend(excl)
 body.append("")
 body.append("## 1 判定摘要")
 body.append("")
 body.append(FENCE)
 body+=counts+fails+crashed+post
 if faildetail:
  body.append("# FAIL detail lines:")
  body+=faildetail
 body.append(FENCE)
 body.append("")
 body.append("## 2 记录项（RECORD 行）")
 body.append("")
 body.append(FENCE)
 body+=records
 body.append(FENCE)
 body.append("")
 body.append("## 3 说明")
 body.append("")
 body.append("- 本文件是正式门禁输出的抽取；FAIL 照实保留，不修脚本、不重跑（冻结期规则）。")
 body.append("- 覆盖检查与证据清单排除了 tmp/、gate/（含 shakedown/gate/）与 trees/；排除列表见第 2 节。")
 body.append("")
 txt=NL.join(body)+NL
 rp=os.path.realpath(OUT)
 if not rp.startswith(os.path.realpath(P05)+os.sep): print("HARD_STOP appendix path"); return 2
 open(OUT,"w",encoding="utf-8").write(txt)
 print("APPENDIX bytes=%d lines=%d"%(len(txt.encode()),len(lines)))
 return 0
if __name__=="__main__": sys.exit(main())
