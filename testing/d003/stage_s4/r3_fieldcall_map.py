#!/usr/bin/env python3
# r3_fieldcall_map.py -- P05-S4 R3-1 field-call assignment (new file, R3).  Reads the discovery_fc gdb logs
# (R3FC marks each entry of S4_Simulation_GetFieldPlane, R3EV marks each malloc/plan/exec wrapper call) and writes
# FIELDCALL_MAP.tsv: for every (route, mode, tree, category, NTH), the field call (1 or 2) in which that call
# happened.  Read-only on the logs.  It writes only the one output file named on the command line.
#
#   python3 -I -B testing/d003/stage_s4/r3_fieldcall_map.py DISCOVERY_FC_DIR OUT_TSV
#
# Use: the injection NTH selects the k-th call of its category.  The judge reads rc1 when the injected call is in
# field call 1 and rc2 when it is in field call 2 (judge_d003.classify inj_call).  This map gives that choice from
# the discovery, not from a guess.  The two trees must give the same map (checked; a difference is an error).
import glob
import os
import re
import sys

LOG = re.compile(r"^(once|twice)-([BF])-([a-z0-9]+)-r1\.log$")
EV_RE = re.compile(r"^R3EV cat=(malloc|plan|exec) nth=(\d+)")
FC_RE = re.compile(r"^R3FC k=(\d+)")


def assign(path):
    """Return {(cat, nth): fc} for one log.  fc is the field call index in force when the event occurred."""
    fc = 0
    out = {}
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            m = FC_RE.match(line)
            if m:
                fc = int(m.group(1))
                continue
            m = EV_RE.match(line)
            if m:
                cat, nth = m.group(1), int(m.group(2))
                out[(cat, nth)] = fc
    return out


def main(argv):
    if len(argv) != 3:
        print("usage: r3_fieldcall_map.py DISCOVERY_FC_DIR OUT_TSV", file=sys.stderr)
        return 2
    disc, out_path = argv[1], argv[2]
    maps = {}
    for path in sorted(glob.glob(os.path.join(disc, "*-r1.log"))):
        m = LOG.match(os.path.basename(path))
        if not m:
            continue
        route, tree, mode = m.group(1), m.group(2), m.group(3)
        maps[(route, mode, tree)] = assign(path)
    # the two trees must agree on the field call of every NTH
    rows = []
    bad = []
    for (route, mode) in sorted({(r, m) for (r, m, t) in maps}):
        mb = maps.get((route, mode, "B"), {})
        mf = maps.get((route, mode, "F"), {})
        if mb != mf:
            bad.append((route, mode))
            continue
        for (cat, nth), fc in sorted(mb.items(), key=lambda kv: (kv[0][0], kv[0][1])):
            rows.append((route, mode, cat, str(nth), str(fc)))
    if bad:
        for r, m in bad:
            print("MISMATCH between trees B and F for route=%s mode=%s" % (r, m), file=sys.stderr)
        return 1
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("# FIELDCALL_MAP.tsv -- P05-S4 R3-1.  Generated by r3_fieldcall_map.py from discovery_fc (no injection).\n")
        fh.write("# field_call = 1 or 2: the call of S4_Simulation_GetFieldPlane in force when this event occurred.\n")
        fh.write("# Identical for trees B and F (checked).  Used to choose inj_call (rc1 or rc2) for the sweep.\n")
        fh.write("route\tmode\tcategory\tnth\tfield_call\n")
        for r in rows:
            fh.write("\t".join(r) + "\n")
    print("rows=%d" % len(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
