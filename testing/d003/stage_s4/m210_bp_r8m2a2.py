#!/usr/bin/env python3
# m210_bp_r8m2a2.py -- P05-S4 R8 M2a2 CONT1 section 7 (M2-10): breakpoints and gdb script generator (R2).
# Scans tree_B/S4/S4.cpp: the Simulation_ComputeLayerModes body (brace matched) and every 'return 20;' inside it;
# checks whether a return check after each FMMGetEpsilon_* call exists in tree B (it is not there in the source: the
# FMM calls return no status).  Writes the gdb script m210_b_r8m2a2_R2.gdb (the R1 script m210_b_r8m2a2.gdb is kept, SUPERSEDED).
# The gdb script is NOT run here.  argv is taken from testing/d003/stage_s4r7/run_m1_r7.py (GRID constant, read below).
# Output: $EV/M210_BREAKPOINTS_R8_M2a2.tsv and the gdb script in testing/d003/stage_s4/m210_b_r8m2a2_R2.gdb
import os
import re
import sys

REPO = os.path.realpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
EV = os.path.join(REPO, "checkpoints", "p05", "evidence", "p05-s4r8", "m2a2")
TREE_B = os.path.join(EV, "tree_B", "S4", "S4.cpp")
RUNNER = os.path.join(REPO, "testing", "d003", "stage_s4r7", "run_m1_r7.py")
GDB_OUT = os.path.join(REPO, "testing", "d003", "stage_s4", "m210_b_r8m2a2_R2.gdb")
TSV_OUT = os.path.join(EV, "M210_BREAKPOINTS_R8_M2a2_R2.tsv")


def function_range(lines, header_line):
    depth = 0
    seen = False
    for i in range(header_line - 1, len(lines)):
        for ch in lines[i]:
            if ch == "{":
                depth += 1
                seen = True
            elif ch == "}":
                depth -= 1
        if seen and depth == 0:
            return header_line, i + 1
    return header_line, len(lines)


def main():
    if os.path.exists(TSV_OUT):
        print("m210_bp_r8m2a2: REFUSED exists (U17)")
        return 2
    with open(TREE_B, encoding="utf-8", errors="replace") as fh:
        lines = fh.read().split("\n")
    # definition line (the declaration at line ~218 ends with ';' and is not matched)
    hdr_lines = [i for i, l in enumerate(lines, 1)
                 if re.match(r"^int Simulation_ComputeLayerModes\(.*\)\s*\{", l)]
    if len(hdr_lines) != 1:
        print("m210_bp_r8m2a2: REFUSED definition of Simulation_ComputeLayerModes found %d times" % len(hdr_lines))
        return 3
    hdr = hdr_lines[0]
    start, end = function_range(lines, hdr)
    rets = [i for i in range(start, end + 1) if re.search(r"return\s+20\s*;", lines[i - 1])]
    # FMM call sites inside the body; does any of them have a return check?
    fmm_calls = [i for i in range(start, end + 1) if re.search(r"FMMGetEpsilon_\w+\s*\(", lines[i - 1])]
    fmm_checked = []
    for i in fmm_calls:
        cur = lines[i - 1].strip()
        if (re.match(r"^\s*if\s*\(.*FMMGetEpsilon", cur) or
            re.match(r"^\s*\w+\s*=\s*FMMGetEpsilon", cur) or
            re.match(r"^\s*int\s+\w+\s*=\s*FMMGetEpsilon", cur)):
            fmm_checked.append(i)
    b_has_fmm_check = "YES" if fmm_checked else "B 无此检查 [源码]"
    # argv from the R7 M1 runner
    with open(RUNNER, encoding="utf-8") as fh:
        grid_line = next((l for l in fh if re.match(r"^GRID\s*=", l)), "")
    argv = re.findall(r'"([^"]+)"', grid_line)
    if argv != ["pattern", "both", "4", "3"]:
        print("m210_bp_r8m2a2: REFUSED argv in runner differs from the recorded GRID: %r" % argv)
        return 3
    with open(TSV_OUT, "x", encoding="utf-8") as fh:
        fh.write("# M210_BREAKPOINTS_R8_M2a2_R2 -- tree B, Simulation_ComputeLayerModes body %d-%d\n" % (start, end))
        fh.write("line\tkind\ttext\n")
        for i in rets:
            fh.write("%d\tRETURN_20\t%s\n" % (i, lines[i - 1].strip()))
        for i in fmm_calls:
            fh.write("%d\tFMM_CALL\t%s\n" % (i, lines[i - 1].strip()))
        fh.write("# RETURN_20_SITES=%d FMM_CALL_SITES=%d B_HAS_FMM_RETURN_CHECK=%s\n" % (len(rets), len(fmm_calls), b_has_fmm_check))
        fh.write("# ARGV_FROM_RUNNER=%s\n" % " ".join(argv))
    with open(GDB_OUT, "w", encoding="utf-8") as fh:
        fh.write("# m210_b_r8m2a2_R2.gdb -- P05-S4 R8 M2a2 CONT1 section 7 (M2-10 R2). Generated by m210_bp_r8m2a2.py.\n")
        fh.write("# NOT RUN in M2a2 (no gdb run).  Breakpoints: every 'return 20;' in tree B Simulation_ComputeLayerModes.\n")
        fh.write("# B FMM return check: %s\n" % b_has_fmm_check)
        fh.write("# argv from testing/d003/stage_s4r7/run_m1_r7.py GRID: %s\n" % " ".join(argv))
        fh.write("set pagination off\nset confirm off\n")
        for i in rets:
            fh.write("break S4/S4.cpp:%d\n" % i)
            fh.write("commands\n")
            fh.write('  printf "M210_HIT: Simulation_ComputeLayerModes line %d returns 20\\n"\n' % i)
            fh.write("  continue\n")
            fh.write("end\n")
        fh.write("run\nquit\n")
    print("m210_bp_r8m2a2: returns=%d fmm_calls=%d b_fmm_return_check=%s argv=%s" %
          (len(rets), len(fmm_calls), b_has_fmm_check, " ".join(argv)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
