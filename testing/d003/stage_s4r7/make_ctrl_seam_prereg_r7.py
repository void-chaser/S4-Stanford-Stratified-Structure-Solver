#!/usr/bin/env python3
"""P05-S4 R7 cont6 U65(b): the CTRL_SEAM control pre-registration (new file; writes OUT only; refuses if OUT exists).

Four rows, one per seam driver that R7 runs (U61): seamF-F, seamF-F2, fmmret-F, fmmret-F2.
Each row: mode fft (a valid FMM mode; the historical R4 controls ran with mode fft, p05-s4r4 control_runs), NG 9, no injection,
expected CONTROL_OK.  The expected values come from CONTROL_R4.tsv (seamF and fmmret-F rows, both CONTROL_OK, rc 0, hit 0);
F2 rows have no historical control and copy the F expectation of the same library (stated, and covered by the F/F2 comparison).
The file records its own sha256 of the rows and the UTC time of creation (U65(b): registered before its run).

Usage (through safe_run):  python3 -I -B testing/d003/stage_s4r7/make_ctrl_seam_prereg_r7.py OUT.tsv
"""
import datetime
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
CONTROL_R4 = os.path.join(REPO, "checkpoints", "p05", "registries", "s4r4", "CONTROL_R4.tsv")
ROWS = [
    # driver name, tree, mode, expected, historical source line
    ("seamF-F", "F", "fft", "CONTROL_OK", "seamF"),
    ("seamF-F2", "F2", "fft", "CONTROL_OK", "seamF"),
    ("fmmret-F", "F", "fft", "CONTROL_OK", "fmmret-F"),
    ("fmmret-F2", "F2", "fft", "CONTROL_OK", "fmmret-F"),
]


def observed_field(name):
    """The observed=<class> cell of the CONTROL_R4 row whose first column is the library name (exact match)."""
    with open(CONTROL_R4, encoding="utf-8") as fh:
        for raw in fh:
            cells = raw.rstrip("\n").split("\t")
            if cells and cells[0] == name:
                for cell in cells:
                    if cell.startswith("observed="):
                        return cell[len("observed="):]
    return None


def main(argv):
    if len(argv) != 2:
        raise SystemExit("usage: make_ctrl_seam_prereg_r7.py OUT.tsv")
    out = argv[1]
    if not os.path.isabs(out):
        raise SystemExit("REFUSED: OUT must be an absolute path under the evidence directory")
    if os.path.exists(out):
        raise SystemExit("REFUSED: exists (U17): %s" % out)
    lines = ["# REGISTRY_S4_PRE_R7_M2_CTRL_SEAM.tsv -- P05-S4 R7 cont6 U65(b) seam controls (generated by make_ctrl_seam_prereg_r7.py).",
             "# Status: INFLUENCED (expected values are the historical R4 CONTROL_R4 observations of seamF and fmmret-F).",
             "# source CONTROL_R4 sha256=%s" % hashlib.sha256(open(CONTROL_R4, "rb").read()).hexdigest(),
             "point_id\tdriver\ttree\tmode\tNG\trequest\tinj_call\texpected_class\texpected_source\tstatus"]
    for name, tree, mode, expected, src in ROWS:
        obs = observed_field(src)
        if obs != expected:
            raise SystemExit("REFUSED: CONTROL_R4 observed for %s is %r, not %s" % (src, obs, expected))
        pid = "CTRL-SEAM-%s" % name
        lines.append("\t".join([pid, name, tree, mode, "9", "none", "-", expected,
                                "CONTROL_R4 %s observed=%s" % (src, obs), "INFLUENCED"]))
    body = "\n".join(lines) + "\n"
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    body += "# registered_utc=%s\n" % stamp
    body += "# rows_sha256=%s\n" % hashlib.sha256(body.encode("utf-8")).hexdigest()
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(body)
    print("wrote %d rows -> %s  utc=%s" % (len(ROWS), out, stamp))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
